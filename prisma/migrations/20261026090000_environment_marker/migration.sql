-- @migration: constraining it INSERTs a row, which the classifier cannot reason about and fails closed on; the column additions themselves are additive
-- @precedes-deploy: the deploy that follows makes sendNotification refuse when this row cannot be read, so the row must exist on production BEFORE that code is live or production email stops
--
-- WHICH DATABASE AM I — asked of the database itself.
--
-- Until 2026-10-26 there was one database and dev shared it with production. There is a separate
-- gate project now, and three guards need to know which one they are talking to: gatePrisma (so a
-- gate cannot write fixtures to the live tenant, which on 25 October put a gate's trial length on
-- the public site as a real offer), and sendNotification (so a gate can drive a real signup
-- end to end without an email leaving the building).
--
-- ── WHY THE DEFAULT IS 'production' AND NOT 'test' ────────────────────────────────────────────
-- This SQL cannot see which database it is running against, so it writes the SAME row everywhere
-- and the DEFAULT decides what an unconfigured database claims to be. Both directions were
-- considered and only one fails safe:
--
--   default 'production'  a new database is treated as production. Gates REFUSE it (safe — the
--                         worst case is work not done). Sends are allowed, and the worst case
--                         there is a brand-new empty database with no recipients in it.
--   default 'test'        a new database is treated as a test one. Sends would be refused on
--                         PRODUCTION the moment this applied, which is the outcome that matters.
--
-- So production needs no manual step: it applies this and carries on. The gate database is
-- flipped to 'test' explicitly afterwards, which is a deliberate act on one database.
--
-- updated_at is supplied because @updatedAt is generated by the Prisma CLIENT, not the database —
-- the ProgrammeSettings migration failed on exactly this and it is the same shape here.
CREATE TYPE "EnvironmentKind" AS ENUM ('production', 'test');

CREATE TABLE "Environment" (
  "id"         TEXT NOT NULL DEFAULT 'singleton',
  "kind"       "EnvironmentKind" NOT NULL DEFAULT 'production',
  "label"      TEXT,
  "updated_at" TIMESTAMP(3) NOT NULL,
  CONSTRAINT "Environment_pkey" PRIMARY KEY ("id")
);

INSERT INTO "Environment" ("id", "updated_at") VALUES ('singleton', now()) ON CONFLICT ("id") DO NOTHING;
