-- @migration: constraining it INSERTs a row, which the classifier cannot reason about and fails closed on; the column additions themselves are additive
-- @precedes-deploy: the deploy that follows reads ProgrammeSettings on the signup, checkout and marketing paths and assumes the singleton row exists, so the row must be in place before that code is live
--
-- THE SINGLETON, AND WHETHER THE PUBLIC SITE AGREES WITH IT.
--
-- ProgrammeSettings was created with the affiliate programme and has NEVER HAD A ROW. Every
-- default on it has therefore been a default nobody has ever read. The trial length moves onto it
-- in this slice, so the row stops being theoretical: it is what Checkout seeds trial_period_days
-- from and what the homepage prints.
--
-- The INSERT names NO SETTING — every programme column takes its schema default, so each default
-- lives in exactly one place (the schema) and not a second time in this file. That is the whole
-- point of the slice; writing `trial_days = 30` here would reintroduce the defect on day one.
--
-- updated_at IS THE EXCEPTION, and it is the first attempt at this migration failing that proved
-- it: `@updatedAt` is generated by the PRISMA CLIENT, not by the database, so the column is NOT
-- NULL with no default and a raw INSERT must supply it. It is a timestamp, not a term.
--
-- ── TWO COLUMNS, BECAUSE "SAVED" AND "THE PUBLIC SITE AGREES" ARE DIFFERENT QUESTIONS ─────────
-- The marketing pages are statically generated and refreshed on demand when the setting is saved.
-- A save that succeeds while the revalidation fails leaves the Engine Room showing 30 and
-- greasedesk.com promising 60, with nothing anywhere to notice — the worst outcome available.
-- So the result of the refresh is recorded, in three honest states:
--   both NULL                  — never attempted (the row as it is born)
--   copy_revalidated_at set,
--     copy_revalidate_error NULL — the public pages were refreshed at that moment
--   copy_revalidate_error set  — the last attempt FAILED, and the live site may still be stale
-- Cleared on success, so the error never outlives the fault it describes.
ALTER TABLE "ProgrammeSettings" ADD COLUMN "copy_revalidated_at" TIMESTAMP(3);
ALTER TABLE "ProgrammeSettings" ADD COLUMN "copy_revalidate_error" TEXT;

INSERT INTO "ProgrammeSettings" ("id", "updated_at") VALUES ('singleton', now()) ON CONFLICT ("id") DO NOTHING;
