/**
 * File: scripts/demo-profile-extract.mjs
 * READ-ONLY against TMBS. Emits lib/demo/profile.ts — the ONLY thing the demo generator ever reads.
 *
 * ── WHY THE PROFILE IS A CHECKED-IN FILE AND NOT A LIVE READ ────────────────────────────────────
 * If the generator queried TMBS at generation time, the promise that nothing identifying can
 * survive would rest on runtime discipline forever — every future edit a chance to widen a select.
 * Emitting a file makes the promise rest on ONE reviewable artefact that a human reads once. This
 * script is the only thing that ever touches the real tenant, and it is not shipped as a dependency
 * of anything.
 *
 * ── WHAT IS DERIVED AND WHAT IS AUTHORED ────────────────────────────────────────────────────────
 * DERIVED (aggregates only, never rows): the numeric shape — hours, money, durations, mileage,
 * vehicle age, counts per job, weekday and start-hour spread, return interval, comeback rate.
 * AUTHORED (never from TMBS): every NAME. Vehicle makes and models, catalogue titles, customer and
 * street name pools, and the seasonal index. TMBS is a MINI specialist with its own service tiering
 * — reproducing either would make the demo recognisably theirs and, worse, wrong for the general
 * independent it is meant to portray.
 *
 * ── QUANTILES ARE ROUNDED ON PURPOSE ────────────────────────────────────────────────────────────
 * An unrounded p90 or max IS a single real invoice's total. Rounding money to £5, hours to a
 * quarter and mileage to 1,000 costs the generator nothing and means no figure in the file is a
 * transcription of one job.
 *
 * ── DETERMINISM ─────────────────────────────────────────────────────────────────────────────────
 * No timestamp, no run id, keys emitted in a fixed order. Re-running against unchanged data must
 * produce a byte-identical file, and the gate asserts exactly that.
 *
 *   node scripts/demo-profile-extract.mjs            # writes lib/demo/profile.ts
 *   node scripts/demo-profile-extract.mjs --stdout   # prints, writes nothing
 */
